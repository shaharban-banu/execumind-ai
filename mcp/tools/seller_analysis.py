"""
Seller Analysis MCP Tool.

Provides business capabilities related to seller
performance, revenue, and fulfillment quality.

The Data Intelligence Agent uses these functions
instead of generating SQL directly.
"""

from typing import Any

from mcp.tools.query_db import query_db
from utils.logger import logger


def seller_summary(user_id:int,mode: str = "historical"):
    """
    Retrieve overall seller statistics.
    """
    sql = """
    SELECT
        COUNT(DISTINCT seller_id) AS total_sellers,
        SUM(quantity) AS total_items_sold,
        ROUND(SUM(order_item_value)::numeric, 2) AS total_revenue
    FROM order_items oi
    JOIN orders o ON oi.order_id = o.order_id
    WHERE o.user_id = :user_id;
    """

    logger.info("Executing seller summary")

    try:
        return query_db(sql, {"user_id": user_id},mode)
    except Exception as exc:
        logger.exception(
            "Seller summary query failed: %s",
            exc,
        )
        raise RuntimeError(
            "Failed to retrieve seller summary."
        ) from exc


def top_sellers(user_id:int,limit: int = 10,mode: str = "historical"):
    """
    Retrieve top sellers by revenue.
    """
    limit = max(1, min(limit, 100))

    sql = f"""
    SELECT
        seller_id,
        SUM(quantity) AS items_sold,
        ROUND(SUM(order_item_value)::numeric, 2) AS revenue
    FROM order_items oi
    JOIN orders o ON oi.order_id = o.order_id
    WHERE o.user_id = :user_id
    GROUP BY seller_id
    ORDER BY revenue DESC
    LIMIT {limit};
    """

    logger.info("Executing top sellers")

    try:
        return query_db(sql, {"user_id": user_id},mode)
    except Exception as exc:
        logger.exception(
            "Top sellers query failed: %s",
            exc,
        )
        raise RuntimeError(
            "Failed to retrieve top sellers."
        ) from exc


