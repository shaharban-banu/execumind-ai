def seller_delivery_performance(user_id:int,mode: str = "historical"):
    """
    Retrieve delivery performance by seller.
    """
    sql = """
    SELECT
        oi.seller_id,

        COUNT(*) AS total_orders,

        ROUND(
            AVG(
                EXTRACT(
                    EPOCH FROM (
                        o.delivered_date - o.order_date
                    )
                ) / 86400
            )::numeric,
            2
        ) AS average_delivery_days,

        SUM(
            CASE
                WHEN o.delivered_date >
                     o.estimated_delivery_date
                THEN 1
                ELSE 0
            END
        ) AS late_deliveries

    FROM order_items oi

    JOIN orders o
        ON oi.order_id = o.order_id

    WHERE o.delivered_date IS NOT NULL

    AND o.user_id = :user_id

    GROUP BY oi.seller_id

    ORDER BY late_deliveries DESC;
    """

    logger.info("Executing seller delivery performance")

    try:
        return query_db(sql,{"user_id": user_id}, mode)
    except Exception as exc:
        logger.exception(
            "seller delivery performance query failed: %s",
            exc,
        )
        raise RuntimeError(
            "Failed to retrieve seller delivery performance."
        ) from exc


def sellers_by_state(user_id:int,mode: str = "historical"):
    """
    Retrieve seller distribution by state.
    """
    sql = """
    SELECT
        seller_state,
        COUNT(*) AS total_sellers
    FROM sellers
    WHERE user_id = :user_id
    GROUP BY seller_state
    ORDER BY total_sellers DESC;
    """

    logger.info("Executing sellers by state")

    try:
        return query_db(sql, {"user_id": user_id},mode)
    except Exception as exc:
        logger.exception(
            "sellers by state query failed: %s",
            exc,
        )
        raise RuntimeError(
            "Failed to retrieve sellers by state."
        ) from exc